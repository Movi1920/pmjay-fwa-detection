SELECT $time_before_delete;

-- Step 3: Simulate an accidental deletion
-- (Delete Karnataka fraud claims as if a junior analyst made an error)
DELETE FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS
WHERE IS_FRAUD_FLAG = 'Y'
  AND CLAIM_ID IN (
      SELECT f.CLAIM_ID
      FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f
      JOIN PMJAY_FWA_DB.CLAIMS.DIM_HOSPITALS h ON f.HOSPITAL_ID = h.HOSPITAL_ID
