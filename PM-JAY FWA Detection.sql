-- 6a: Providers Consistently Billing Above Approved Rate
SELECT 
    h.HOSPITAL_NAME,
    h.STATE,
    COUNT(*) AS total_claims,
    ROUND(AVG(f.BILLED_AMOUNT_INR), 2) AS avg_billed,
    ROUND(AVG(f.APPROVED_RATE_INR), 2) AS avg_approved,
    ROUND(AVG(f.BILLED_AMOUNT_INR - f.APPROVED_RATE_INR), 2) AS avg_overbill,
    ROUND(AVG(f.BILLED_AMOUNT_INR) * 100.0 / NULLIF(AVG(f.APPROVED_RATE_INR), 0), 2) AS billing_ratio_pct
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f
JOIN PMJAY_FWA_DB.CLAIMS.DIM_HOSPITALS h ON f.HOSPITAL_ID = h.HOSPITAL_ID
WHERE f.BILLED_AMOUNT_INR > f.APPROVED_RATE_INR
GROUP BY h.HOSPITAL_NAME, h.STATE
HAVING COUNT(*) > 100
ORDER BY avg_overbill DESC
LIMIT 20;


-- 6b: Duplicate Claim Detection
SELECT 
    f1.BENEFICIARY_ID,
    f1.PACKAGE_CODE,
    f1.HOSPITAL_ID,
    f1.CLAIM_DATE AS claim_date_1,
    f2.CLAIM_DATE AS claim_date_2,
    DATEDIFF('day', f1.CLAIM_DATE, f2.CLAIM_DATE) AS days_apart,
    f1.BILLED_AMOUNT_INR AS amount_1,
    f2.BILLED_AMOUNT_INR AS amount_2
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f1
JOIN PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f2
    ON f1.BENEFICIARY_ID = f2.BENEFICIARY_ID
    AND f1.PACKAGE_CODE = f2.PACKAGE_CODE
    AND f1.CLAIM_DATE < f2.CLAIM_DATE
    AND DATEDIFF('day', f1.CLAIM_DATE, f2.CLAIM_DATE) <= 30
WHERE f1.CLAIM_ID != f2.CLAIM_ID
ORDER BY days_apart
LIMIT 20;

-- 6c: Phantom Surgery Detection (impossible length of stay)
SELECT 
    f.CLAIM_ID,
    h.HOSPITAL_NAME,
    h.STATE,
    p.PROCEDURE_NAME,
    f.CLAIM_DATE,
    f.DISCHARGE_DATE,
    f.LENGTH_OF_STAY,
    f.BILLED_AMOUNT_INR
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f
JOIN PMJAY_FWA_DB.CLAIMS.DIM_HOSPITALS h ON f.HOSPITAL_ID = h.HOSPITAL_ID
JOIN PMJAY_FWA_DB.CLAIMS.DIM_PACKAGES p ON f.PACKAGE_CODE = p.PACKAGE_CODE
WHERE f.LENGTH_OF_STAY = 0
   OR (f.DISCHARGE_DATE < f.CLAIM_DATE)
   OR (f.LENGTH_OF_STAY > 30)
ORDER BY f.LENGTH_OF_STAY DESC
LIMIT 20;

-- 6d: Ghost Beneficiary Detection (claiming from multiple states)
SELECT 
    f.BENEFICIARY_ID,
    b.FULL_NAME,
    b.STATE AS registered_state,
    COUNT(DISTINCT h.STATE) AS states_claimed_from,
    COUNT(*) AS total_claims,
    SUM(f.BILLED_AMOUNT_INR) AS total_billed,
    LISTAGG(DISTINCT h.STATE, ', ') AS claim_states
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f
JOIN PMJAY_FWA_DB.CLAIMS.DIM_BENEFICIARIES b ON f.BENEFICIARY_ID = b.BENEFICIARY_ID
JOIN PMJAY_FWA_DB.CLAIMS.DIM_HOSPITALS h ON f.HOSPITAL_ID = h.HOSPITAL_ID
GROUP BY f.BENEFICIARY_ID, b.FULL_NAME, b.STATE
HAVING COUNT(DISTINCT h.STATE) >= 3
ORDER BY states_claimed_from DESC, total_billed DESC
LIMIT 20;

-- 6e: Rolling Fraud Rate by Hospital (Window Function)
SELECT 
    HOSPITAL_ID,
    CLAIM_DATE,
    CLAIM_STATUS,
    IS_FRAUD_FLAG,
    COUNT(*) OVER (PARTITION BY HOSPITAL_ID 
                   ORDER BY CLAIM_DATE 
                   ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS rolling_30day_claims,
    SUM(CASE WHEN IS_FRAUD_FLAG = 'Y' THEN 1 ELSE 0 END) 
        OVER (PARTITION BY HOSPITAL_ID 
              ORDER BY CLAIM_DATE 
              ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS rolling_fraud_count,
    ROUND(SUM(CASE WHEN IS_FRAUD_FLAG = 'Y' THEN 1 ELSE 0 END) 
        OVER (PARTITION BY HOSPITAL_ID 
              ORDER BY CLAIM_DATE 
              ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) * 100.0 /
    NULLIF(COUNT(*) OVER (PARTITION BY HOSPITAL_ID 
                          ORDER BY CLAIM_DATE 
                          ROWS BETWEEN 29 PRECEDING AND CURRENT ROW), 0), 2) AS rolling_fraud_pct
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS
ORDER BY HOSPITAL_ID, CLAIM_DATE
LIMIT 20;


-- 6f: CTE-Based Suspicious Claim Summary
WITH fraud_summary AS (
    SELECT 
        h.STATE,
        h.HOSPITAL_TYPE,
        COUNT(*) AS total_claims,
        SUM(CASE WHEN f.IS_FRAUD_FLAG = 'Y' THEN 1 ELSE 0 END) AS fraud_claims,
        SUM(f.BILLED_AMOUNT_INR) AS total_billed,
        SUM(CASE WHEN f.IS_FRAUD_FLAG = 'Y' THEN f.BILLED_AMOUNT_INR ELSE 0 END) AS fraud_amount
    FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS f
    JOIN PMJAY_FWA_DB.CLAIMS.DIM_HOSPITALS h ON f.HOSPITAL_ID = h.HOSPITAL_ID
    GROUP BY h.STATE, h.HOSPITAL_TYPE
)
SELECT 
    STATE,
    HOSPITAL_TYPE,
    total_claims,
    fraud_claims,
    ROUND(fraud_claims * 100.0 / NULLIF(total_claims, 0), 2) AS fraud_rate_pct,
    ROUND(total_billed / 1000000, 2) AS total_billed_millions,
    ROUND(fraud_amount / 1000000, 2) AS fraud_amount_millions
FROM fraud_summary
WHERE fraud_claims > 0
ORDER BY fraud_rate_pct DESC
LIMIT 20;

-- 6g: Overall Fraud Financial Impact Summary
SELECT
    COUNT(*) AS total_claims,
    SUM(CASE WHEN IS_FRAUD_FLAG = 'Y' THEN 1 ELSE 0 END) AS total_fraud_claims,
    ROUND(SUM(CASE WHEN IS_FRAUD_FLAG = 'Y' THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS overall_fraud_rate_pct,
    ROUND(SUM(BILLED_AMOUNT_INR) / 10000000, 2) AS total_billed_crores,
    ROUND(SUM(CASE WHEN IS_FRAUD_FLAG = 'Y' THEN BILLED_AMOUNT_INR ELSE 0 END) / 10000000, 2) AS fraud_amount_crores,
    ROUND(SUM(CASE WHEN IS_FRAUD_FLAG = 'Y' THEN BILLED_AMOUNT_INR ELSE 0 END) * 100.0 / NULLIF(SUM(BILLED_AMOUNT_INR), 0), 2) AS fraud_amount_pct
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS;

