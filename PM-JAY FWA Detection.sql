      LIMIT 500
  );

-- Step 4: Confirm rows are gone
SELECT COUNT(*) AS count_after_delete FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS;

-- Step 5: Use Time Travel to query data AS IT WAS before deletion
SELECT COUNT(*) AS count_before_delete
FROM PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS
AT (TIMESTAMP => $time_before_delete);

-- Step 6: Recover the deleted rows using Time Travel
INSERT INTO PMJAY_FWA_DB.CLAIMS.FACT_CLAIMS
    (CLAIM_ID, BENEFICIARY_ID, HOSPITAL_ID, PACKAGE_CODE,
     CLAIM_DATE, DISCHARGE_DATE, LENGTH_OF_STAY,
